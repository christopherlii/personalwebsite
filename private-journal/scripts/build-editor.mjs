import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: [new URL('../editor/live-editor.js', import.meta.url).pathname],
  outfile: new URL('../public/live-editor.js', import.meta.url).pathname,
  bundle: true, format: 'esm', minify: true, target: 'es2022',
  external: ['./markdown.js'], legalComments: 'none', metafile: true,
  banner: { js: '// Generated by npm run build:editor. Licenses: ./vendor/live-editor-LICENSE.txt' }
});
const packages = [...new Set(Object.keys(result.metafile.inputs).map(path => path.match(/(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean))].sort();
const licenses = await Promise.all(packages.map(async name => {
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt']) {
    try { return `${name}\n${await readFile(new URL(`../node_modules/${name}/${file}`, import.meta.url), 'utf8')}`; }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  throw new Error(`No license file found for bundled package ${name}`);
}));
await writeFile(new URL('../public/vendor/live-editor-LICENSE.txt', import.meta.url), licenses.join('\n\n'));
